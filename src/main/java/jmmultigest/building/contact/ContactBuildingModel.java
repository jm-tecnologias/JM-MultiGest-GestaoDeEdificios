package jmmultigest.building.contact;

/**
 *
 * @author JM-Tecnologias
 */
public class ContactBuildingModel {
    private int id;
    private String phone;
    private String email;
    private String website;
    private int building_id;
    private boolean status;
    private String created_at;
    private String updated_at;

    public ContactBuildingModel() {
    }

    public ContactBuildingModel(int id, String phone, String email, String website, int building_id, boolean status) {
        this.id = id;
        this.phone = phone;
        this.email = email;
        this.website = website;
        this.building_id = building_id;
        this.status = status;
    }
    
    

    public int getId() {
        return id;
    }

    public void setId(int id) {
        this.id = id;
    }

    public String getPhone() {
        return phone;
    }

    public void setPhone(String phone) {
        this.phone = phone;
    }

    public String getEmail() {
        return email;
    }

    public void setEmail(String email) {
        this.email = email;
    }

    public String getWebsite() {
        return website;
    }

    public void setWebsite(String website) {
        this.website = website;
    }

    public int getBuilding_id() {
        return building_id;
    }

    public void setBuilding_id(int building_id) {
        this.building_id = building_id;
    }

    public boolean isStatus() {
        return status;
    }

    public void setStatus(boolean status) {
        this.status = status;
    }

    public String getCreated_at() {
        return created_at;
    }

    public void setCreated_at(String created_at) {
        this.created_at = created_at;
    }

    public String getUpdated_at() {
        return updated_at;
    }

    public void setUpdated_at(String updated_at) {
        this.updated_at = updated_at;
    }
    
    
}
